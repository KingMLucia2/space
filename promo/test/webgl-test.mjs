import { createRequire } from 'module';
import http from 'http'; import fs from 'fs'; import path from 'path';
const require = createRequire(import.meta.url);
const { chromium } = require('/opt/node-tools/node_modules/playwright');
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const types = { '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.json': 'application/json', '.png': 'image/png', '.jpg': 'image/jpeg' };
const server = http.createServer((req, res) => { const f = path.join(root, decodeURIComponent(req.url.split('?')[0])); if (!f.startsWith(root) || !fs.existsSync(f)) { res.writeHead(404); return res.end(); } res.writeHead(200, { 'Content-Type': types[path.extname(f)] || 'application/octet-stream' }); fs.createReadStream(f).pipe(res); }).listen(0);
const port = server.address().port;
const args = process.argv[2] ? process.argv[2].split(' ') : ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'];
const browser = await chromium.launch({ args });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
page.on('console', m => console.log('[page]', m.text())); page.on('pageerror', e => console.log('[err]', e.message));
await page.goto(`http://localhost:${port}/test/webgl-test.html`);
await page.waitForFunction('window.ready === true', null, { timeout: 60000 });
console.log(await page.evaluate('glInfo()'));
let t0 = Date.now();
for (let i = 0; i < 5; i++) await page.evaluate(`renderFrame(${i / 24})`);
const per = (Date.now() - t0) / 5; t0 = Date.now();
const buf = await page.screenshot({ type: 'jpeg', quality: 92 });
console.log('render ms/frame', per.toFixed(0), 'screenshot ms', Date.now() - t0, 'bytes', buf.length);
fs.writeFileSync(path.join(root, 'test/webgl-test.jpg'), buf);
await browser.close(); server.close();
